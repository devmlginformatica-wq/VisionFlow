import { z } from 'zod'

const optionalEmail = z.union([
    z.string().trim().email('Informe um e-mail válido.'),
    z.literal(''),
])

export const clienteSchema = z.object({
    id: z.number().nullable(),
    name: z.string().trim().min(1, 'Informe o nome ou razão social.'),
    legalName: z.string(),
    tradeName: z.string(),
    taxId: z.string(),
    personType: z.enum(['PF', 'PJ']),
    stateRegistration: z.string(),
    buyerContact: z.string(),
    buyerEmail: optionalEmail,
    billingContact: z.string(),
    invoiceEmail: optionalEmail,
    commercialPhone: z.string().trim().min(1, 'Informe o telefone comercial.'),
    mobilePhone: z.string(),
    otherPhone: z.string(),
    prospect: z.boolean(),
    status: z.string(),
    registrationStatus: z.string(),
    purchaseStatus: z.string(),
    openedAt: z.string(),
    indicatorColor: z.enum(['verde', 'vermelho']),
    addressSummary: z.string(),
    fullAddress: z.string(),
    lastOrder: z.string().nullable(),
    lastAttendance: z.string().nullable(),
    carrierId: z.number().nullable(),
    paymentConditionId: z.number().nullable(),
    paymentMethodId: z.number().nullable(),
    priceTableId: z.number().nullable(),
    lastVisit: z.string(),
    integrationId: z.string(),
    creditLimit: z.number().min(0, 'O limite não pode ser negativo.'),
    userNotes: z.string(),
    erpNotes: z.string(),
    addresses: z.array(z.object({
        id: z.number(),
        type: z.string(),
        purpose: z.string(),
        zipCode: z.string(),
        street: z.string(),
        number: z.string(),
        complement: z.string(),
        district: z.string(),
        city: z.string(),
        state: z.string(),
        reference: z.string(),
        deliveryRestrictions: z.string(),
    })),
    titles: z.array(z.object({
        id: z.number(),
        title: z.string(),
        installment: z.string(),
        documentType: z.string(),
        series: z.string(),
        issueDate: z.string(),
        dueDate: z.string(),
        openAmount: z.number(),
    })),
})

export type ClienteFormValues = z.infer<typeof clienteSchema>